export function countryFromTimeZone(timeZone: string | undefined): CountryName {
  if (!timeZone) return "Somewhere else";
  return TZ_COUNTRY[timeZone] ?? "Somewhere else";
}

export function isCountry(value: string): value is CountryName {
  return (COUNTRIES as readonly string[]).includes(value);
}
